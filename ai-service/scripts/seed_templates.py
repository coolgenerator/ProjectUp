def seed_templates():
    """Seed database with comprehensive template library"""
    db = SessionLocal()
    service = TemplateService(db)

    try:
        logger.info(f"Starting template seeding... ({len(TEMPLATES)} templates)")

        created_count = service.bulk_create_templates(TEMPLATES)

        logger.info(f"✓ Successfully created {created_count} templates")

        # Display summary by category
        categories = service.get_all_categories()
        logger.info("\n📚 Template Library Summary:")
        for category in categories:
            logger.info(f"  {category['icon']} {category['name']}: {category['count']} templates")

    except Exception as e:
        logger.error(f"Error seeding templates: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_templates()
