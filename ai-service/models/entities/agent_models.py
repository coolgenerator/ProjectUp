from typing import List, Optional
from pydantic import BaseModel, Field


class AgentRequest(BaseModel):
    """AgentRequest represents a request to the AI agent"""
    message: str = Field(..., description="User message")

    class Config:
        from_attributes = True


class AgentResponse(BaseModel):
    """AgentResponse represents a response from the AI agent"""
    response: str = Field(..., description="Agent response")

    class Config:
        from_attributes = True


class AgentConfig(BaseModel):
    """AgentConfig represents configuration for an AI agent"""
    name: str = Field(..., description="Agent name")
    provider: str = Field(..., description="AI provider")
    model: str = Field(..., description="Model name")
    temperature: float = Field(..., description="Temperature setting")
    max_tokens: int = Field(..., description="Maximum tokens")
    memory_size: int = Field(..., description="Memory size")

    class Config:
        from_attributes = True


class ProjectIdea(BaseModel):
    """ProjectIdea represents a project idea generated by the AI"""
    title: str = Field(..., description="Project title")
    description: str = Field(..., description="Project description")
    difficulty: str = Field(..., description="Difficulty level (Beginner, Intermediate, Advanced)")
    estimated_time: str = Field(..., description="Estimated time to complete", alias="estimatedTime")
    estimated_hours_per_week: str = Field(..., description="Estimated hours per week", alias="estimatedHoursPerWeek")
    key_technologies: List[str] = Field(..., description="Key technologies", alias="keyTechnologies")
    key_features: List[str] = Field(..., description="Key features", alias="keyFeatures")
    learning_outcomes: List[str] = Field(..., description="Learning outcomes", alias="learningOutcomes")

    class Config:
        from_attributes = True
        populate_by_name = True


class ProjectIdeaResponse(BaseModel):
    """ProjectIdeaResponse represents the response structure for project ideas"""
    project_ideas: List[ProjectIdea] = Field(..., description="List of project ideas", alias="projectIdeas")

    class Config:
        from_attributes = True
        populate_by_name = True


class RoadmapResource(BaseModel):
    """RoadmapResource represents an educational resource"""
    title: str = Field(..., description="Resource title")
    url: str = Field(..., description="Resource URL")
    type: str = Field(..., description="Resource type (Article, Video, Course, Documentation)")

    class Config:
        from_attributes = True


class BasicRoadmapStep(BaseModel):
    """BasicRoadmapStep represents a roadmap step without resources"""
    title: str = Field(..., description="Step title")
    description: str = Field(..., description="Step description")

    class Config:
        from_attributes = True


class RoadmapStep(BaseModel):
    """RoadmapStep represents a roadmap step with resources"""
    title: str = Field(..., description="Step title")
    description: str = Field(..., description="Step description")
    time_estimate: str = Field(..., description="Time estimate", alias="timeEstimate")
    resources: List[RoadmapResource] = Field(..., description="Resources")

    class Config:
        from_attributes = True
        populate_by_name = True


class BasicRoadmap(BaseModel):
    """BasicRoadmap represents a roadmap without resources"""
    steps: List[BasicRoadmapStep] = Field(..., description="Roadmap steps")

    class Config:
        from_attributes = True


class Roadmap(BaseModel):
    """Roadmap represents a roadmap with resources"""
    steps: List[RoadmapStep] = Field(..., description="Roadmap steps")

    class Config:
        from_attributes = True


class BasicRoadmapResponse(BaseModel):
    """BasicRoadmapResponse represents the response for basic roadmap"""
    roadmap: BasicRoadmap = Field(..., description="Basic roadmap")

    class Config:
        from_attributes = True


class RoadmapResponse(BaseModel):
    """RoadmapResponse represents the response for roadmap with resources"""
    roadmap: Roadmap = Field(..., description="Roadmap")

    class Config:
        from_attributes = True


class StepResources(BaseModel):
    """StepResources represents resources for a specific roadmap step"""
    step_title: str = Field(..., description="Step title", alias="stepTitle")
    resources: List[RoadmapResource] = Field(..., description="Resources")

    class Config:
        from_attributes = True
        populate_by_name = True


class RoadmapResourcesResponse(BaseModel):
    """RoadmapResourcesResponse represents the response for roadmap resources"""
    step_resources: List[StepResources] = Field(..., description="Step resources", alias="stepResources")

    class Config:
        from_attributes = True
        populate_by_name = True


class ChecklistItem(BaseModel):
    """ChecklistItem represents a single item in a project checklist"""
    description: str = Field(..., description="Item description")
    category: str = Field(..., description="Category (Requirements, Setup, Testing, etc.)")
    priority: str = Field(..., description="Priority (High, Medium, Low)")

    class Config:
        from_attributes = True


class ProjectChecklist(BaseModel):
    """ProjectChecklist represents a checklist for project completion"""
    items: List[ChecklistItem] = Field(..., description="Checklist items")

    class Config:
        from_attributes = True


class CurriculumSkill(BaseModel):
    """CurriculumSkill represents a skill developed through the project"""
    name: str = Field(..., description="Skill name")
    description: str = Field(..., description="Skill description")
    level: str = Field(..., description="Skill level (Beginner, Intermediate, Advanced)")

    class Config:
        from_attributes = True


class TopicCategory(BaseModel):
    """TopicCategory represents a category of curriculum topics"""
    name: str = Field(..., description="Category name")
    subcategories: List[str] = Field(..., description="Subcategories")

    class Config:
        from_attributes = True


class CurriculumAlignment(BaseModel):
    """CurriculumAlignment represents how a project aligns with curriculum"""
    topics: List[str] = Field(..., description="Main curriculum topics covered")
    categories: List[TopicCategory] = Field(..., description="Broader categories")
    skills: List[CurriculumSkill] = Field(..., description="Skills developed")

    class Config:
        from_attributes = True


class ProjectRoadmapWithChecklist(BaseModel):
    """ProjectRoadmapWithChecklist represents a roadmap with checklist and alignment"""
    roadmap: Roadmap = Field(..., description="Project roadmap")
    checklist: ProjectChecklist = Field(..., description="Project checklist")
    curriculum_alignment: CurriculumAlignment = Field(..., description="Curriculum alignment", alias="curriculumAlignment")

    class Config:
        from_attributes = True
        populate_by_name = True


class ProjectRoadmapWithChecklistResponse(BaseModel):
    """ProjectRoadmapWithChecklistResponse represents the response for roadmap with checklist"""
    response: ProjectRoadmapWithChecklist = Field(..., description="Complete project roadmap with checklist")

    class Config:
        from_attributes = True
