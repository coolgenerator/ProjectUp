// Request structures for AI project board generation

type GuidedQuestionAnswer struct {
	QuestionID string      `json:"question_id"`
	Answer     interface{} `json:"answer"`
}

type GenerateProjectBoardRequest struct {
	ProjectScenario string                 `json:"project_scenario"` // course, research, product, personal
	ProjectID       uint                   `json:"project_id,omitempty"`
	UserInputs      map[string]interface{} `json:"user_inputs"`
	GuidedAnswers   []GuidedQuestionAnswer `json:"guided_answers"`
	SyllabusText    *string                `json:"syllabus_text,omitempty"`
	SyllabusFile    *string                `json:"syllabus_file,omitempty"` // file path or URL
}

type ProjectPhaseTemplate struct {
	Name              string         `json:"name"`
	Duration          string         `json:"duration"`
	DynamicGeneration bool           `json:"dynamic_generation"`
	Gates             *PhaseGate     `json:"gates,omitempty"`
	TaskTemplates     []TaskTemplate `json:"task_templates,omitempty"`
	AIPrompt          string         `json:"ai_prompt,omitempty"`
	UnlockCondition   string         `json:"unlock_condition,omitempty"`
}

type PhaseGate struct {
	Type                  string   `json:"type"` // approval_required, quality_gate
	Approver              string   `json:"approver,omitempty"`
	ChecklistBeforeSubmit []string `json:"checklist_before_submit,omitempty"`
}

type TaskTemplate struct {
	Title             string   `json:"title"`
	Type              string   `json:"type"` // milestone, deliverable, quality_gate, document
	AIPrompt          string   `json:"ai_prompt,omitempty"`
	RequiredInputs    []string `json:"required_inputs,omitempty"`
	Outputs           []string `json:"outputs,omitempty"`
	AIInteractionMode string   `json:"ai_interaction_mode,omitempty"` // structured_dialogue, guided_framework
	DomainSpecific    bool     `json:"domain_specific,omitempty"`
}

type GeneratedProjectBoard struct {
	Phases      []GeneratedPhase     `json:"phases"`
	Tasks       []GeneratedTask      `json:"tasks"`
	Milestones  []GeneratedMilestone `json:"milestones"`
	Assignments map[string]string    `json:"assignments,omitempty"` // taskId -> userId/placeholderName
}

type GeneratedPhase struct {
	PhaseID   uint            `json:"phase_id,omitempty"`
	Name      string          `json:"name"`
	Status    string          `json:"status"` // pending_generation, generated, active, completed
	Duration  string          `json:"duration"`
	Tasks     []GeneratedTask `json:"tasks"`
	Gates     *PhaseGate      `json:"gates,omitempty"`
	SortOrder int             `json:"sort_order"`
}

type GeneratedTask struct {
	TaskID             uint     `json:"task_id,omitempty"`
	Title              string   `json:"title"`
	Description        string   `json:"description"`
	Type               string   `json:"type"`
	EstimatedHours     *int     `json:"estimated_hours,omitempty"`
	Dependencies       []uint   `json:"dependencies,omitempty"` // task IDs this depends on
	AcceptanceCriteria []string `json:"acceptance_criteria,omitempty"`
	AssignedTo         *string  `json:"assigned_to,omitempty"`
	DueDate            *string  `json:"due_date,omitempty"`
	Priority           string   `json:"priority"` // high, medium, low
	PhaseID            uint     `json:"phase_id"`
}

type GeneratedMilestone struct {
	Name         string   `json:"name"`
	Timing       string   `json:"timing"`
	Deliverables []string `json:"deliverables"`
	DueDate      *string  `json:"due_date,omitempty"`
	Weight       *int     `json:"weight,omitempty"`
}

